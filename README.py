# São questões simples para minha pessoa ter uma ser noção do meu progresso. 

alunos = ["Alice", "Bob", "Charlie", "David", "Eva"]
alunos.append("Frank")
print(alunos)

alunos = ["Alice", "Bob", "Charlie", "David", "Eva"]
alunos.insert(5, "Frank")
print(alunos)

alunos = ["Alice", "Bob", "Charlie", "David", "Eva"]
alunos.remove("Eva")
print(alunos)

alunos = ["Alice", "Bob", "Charlie", "David", "Eva"]
alunos.pop(0)
print(alunos)

alunos = ["David", "Alan", "Charlie", "Bob", "Eva"]
alunos.sort()
print(alunos)
